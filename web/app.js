document.addEventListener('compositionstart', () => { composing = true; });
document.addEventListener('compositionend', () => { composing = false; schedule(); });
document.addEventListener('toggle', (e) => {
  const d = e.target;
  if (d instanceof HTMLDetailsElement && d.dataset.k) {
    if (d.open) {
      UI.open.add(d.dataset.k);
      if (d.classList.contains('live-tail')) {
        const cur = currentSession();
        if (cur?.pane) loadPreview(cur.pane, { mode: pvModeOf(cur.pane), silent: true });
      }
    } else UI.open.delete(d.dataset.k);
  }
}, true);
document.addEventListener('click', (e) => {
  if (UI.muteMenu && !e.target.closest('.mute-wrap')) { UI.muteMenu = false; schedule(); }
  if (UI.slash.open && !e.target.closest('.composer-card')) closeSlashMenu();
});
window.addEventListener('hashchange', route);
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && UI.muteMenu) { UI.muteMenu = false; schedule(); return; }
  if (e.key === 'Escape' && UI.drawer) { closeDrawer(); return; }
  if (e.key === 'Escape' && UI.mobileSessionsOpen) { UI.mobileSessionsOpen = false; schedule(); return; }
  if (e.metaKey || e.ctrlKey || e.altKey) return;
  const t = e.target;
  if (t && (/^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName) || t.isContentEditable)) return;
  if (UI.modal || S.authNeeded) return;
  const n = Number(e.key);
  if (n >= 1 && n <= VIEWS.length) go(VIEWS[n - 1]);
  else if (e.key === 'n') { openSpawnModal(); e.preventDefault(); }
});
const modalEl = $('#modal');
modalEl.addEventListener('close', () => { if (!S.authNeeded) UI.modal = null; });
modalEl.addEventListener('cancel', (e) => { if (S.authNeeded) e.preventDefault(); });
modalEl.addEventListener('click', (e) => { if (e.target.id === 'modal' && !S.authNeeded) closeModal(); });

let vvRaf = 0;
function syncMobileViewport() {
  const narrow = window.innerWidth <= 960;
  const vv = window.visualViewport;
  if (!narrow || !vv) {
    document.documentElement.style.removeProperty('--app-h');
    document.documentElement.classList.remove('kb-open');
    return;
  }
  const hPx = Math.max(240, Math.round(vv.height));
  document.documentElement.style.setProperty('--app-h', `${hPx}px`);
  const kbOpen = window.innerHeight - vv.height > 120;
  const wasKbOpen = document.documentElement.classList.contains('kb-open');
  document.documentElement.classList.toggle('kb-open', kbOpen);
  if (kbOpen && !wasKbOpen) {
    const vp = UI.wsShell?.vp || $('.term-viewport');
    if (vp && vp.scrollHeight - vp.scrollTop - vp.clientHeight < 96) {
      requestAnimationFrame(() => {
        if (vp.isConnected) vp.scrollTop = vp.scrollHeight;
      });
    }
  }
}

function scheduleViewportSync() {
  if (vvRaf) return;
  vvRaf = requestAnimationFrame(() => {
    vvRaf = 0;
    syncMobileViewport();
  });
}

async function boot() {
  syncMobileViewport();
  window.addEventListener('resize', scheduleViewportSync, { passive: true });
  if (window.visualViewport) {
    window.visualViewport.addEventListener('resize', scheduleViewportSync, { passive: true });
    window.visualViewport.addEventListener('scroll', scheduleViewportSync, { passive: true });
  }
  const u = new URL(location.href);
  const tk = u.searchParams.get('token');
  if (tk) {
    localStorage.setItem(TOKEN_KEY, tk);
    u.searchParams.delete('token');
    history.replaceState(null, '', u.pathname + u.search + u.hash);
  }
  route();
  rerender();
  const healthP = pollHealth();
  await loadAll();
  connectSSE();
  await healthP;
  loadModels();
  setInterval(pollHealth, HEALTH_POLL_MS);
  setInterval(pollActivePreview, PREVIEW_POLL_MS);
  setInterval(() => {
    if (document.hidden) return;
    syncStateSilent();
    if (UI.view === 'workspace' && !UI.drawer && !muted() && computeTopSig(alertCount()) === lastTopSig) return;
    const sel = window.getSelection?.();
    if (sel && !sel.isCollapsed && $('.term-viewport')?.contains(sel.anchorNode)) return;
    schedulePassive();
  }, TICK_MS);
  let lastFocusRefreshAt = Date.now();
  document.addEventListener('visibilitychange', () => {
    if (!document.hidden) {
      if (dirtyWhileHidden) rerender();
      lastFocusRefreshAt = Date.now();
      pollHealth();
      syncStateSilent({ refreshActive: true });
      refreshActiveOnResume();
    }
  });
  window.addEventListener('focus', () => {
    const now = Date.now();
    if (document.hidden || (now - lastFocusRefreshAt) < 2000) return;
    lastFocusRefreshAt = now;
    refreshActiveOnResume();
    syncStateSilent();
  });
  window.addEventListener('online', () => {
    lastFocusRefreshAt = Date.now();
    connectSSE();
    pollHealth();
    syncStateSilent({ refreshActive: true });
    refreshActiveOnResume();
  });
}

boot();
