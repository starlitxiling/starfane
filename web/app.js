function schedule() {
  if (document.hidden) { dirtyWhileHidden = true; return; }
  if (renderTimer && !renderPassive) return;
  if (renderTimer) { clearTimeout(renderTimer); renderTimer = 0; }
  renderPassive = false;
  renderTimer = setTimeout(() => { renderTimer = 0; rerender(); }, 32);
}

function schedulePassive() {
  if (document.hidden) { dirtyWhileHidden = true; return; }
  if (renderTimer) return;
  renderPassive = true;
  renderTimer = setTimeout(() => { renderTimer = 0; renderPassive = false; rerender(); }, 120);
}

function compactTranscript(sessionId) {
  if (!sessionId) return;
  if (compactTranscriptEntry(sessionId)) {
    notifyOutputUpdated(sessionId);
    schedule();
  }
}

function computeTopSig(alerts) {
  const cs = connState();
  const liveSessions = rootSessions().filter((s) => !s.is_subagent && s.state !== 'ended' && !!s.pane).length;
  const activePipes = allPipelines().filter((p) => !isFinished(p)).length;
  const pendingVerdicts = [...S.reviews.values()].reduce(
    (n, r) => n + (r.findings || []).filter((f) => f.falsifier?.verdict === 'needs_human' && !f.feedback).length,
    0,
  );
  const upMin = S.uptimeMs != null ? Math.floor(S.uptimeMs / 60000) : -1;
  return `${getLang()}|${resolvedTheme()}|${UI.themePref}|${UI.view}|${cs}|${S.conn}|${S.restarting ? 1 : 0}|${S.uiUpdateAvailable ? 1 : 0}|${S.version}|${S.lastSeq}|${upMin}|${liveSessions}|${alerts}|${activePipes}|${pendingVerdicts}|${notifyTopSig()}`;
}

function renderView() {
  const el = $('#view');
  const appEl = $('#app');
  const isWs = UI.view === 'workspace' && S.loaded;
  const wantFull = UI.view === 'workspace';
  const wantCls = `view${wantFull ? ' full-h' : ''}`;
  if (el.className !== wantCls) el.className = wantCls;
  if (appEl) appEl.classList.toggle('is-ws-view', wantFull);
  if (isWs) {
    mountOrPatchWorkspace(el);
    return;
  }
  let content;
  if (S.authNeeded && !S.loaded) {
    content = emptyState(
      L('需要认证 Token', 'Authentication Token Required'),
      L('请在弹窗中输入本地 daemon 生成的 token，或通过 starfane web 打开控制台。', 'Enter the token generated by the local daemon in the modal, or open the console via starfane web.'),
    );
  } else if (!S.loaded) {
    content = S.loadError
      ? errorBanner(L(`无法连接 starfane daemon：${S.loadError}`, `Cannot connect to starfane daemon: ${S.loadError}`), L('重新连接', 'Reconnect'), loadAll)
      : h('div', { class: 'card' }, skeleton(6));
  } else {
    const fn = { inbox: viewInbox, pipelines: viewPipelines, reviews: viewReviews }[UI.view] || viewInbox;
    content = fn();
  }
  const nodes = [S.loaded && S.loadError ? errorBanner(L(`状态同步异常：${S.loadError}`, `State sync error: ${S.loadError}`), L('重试同步', 'Retry sync'), loadAll) : null, content].filter(Boolean);
  el.replaceChildren(...nodes);
}

function rerender() {
  if (composing) return;
  dirtyWhileHidden = false;
  const a = document.activeElement;
  const fk = a && a.dataset ? a.dataset.draft : null;
  const sel = fk && a.selectionStart != null ? [a.selectionStart, a.selectionEnd] : null;
  const viewEl = $('#view');
  const persistentWsMounted = UI.view === 'workspace' && S.loaded && UI.wsShell?.grid?.parentNode === viewEl;
  const termBox = persistentWsMounted ? null : $('.term-viewport');
  const termScroll = termBox ? {
    sid: termBox.dataset.sid,
    mode: termBox.dataset.mode,
    top: termBox.scrollTop,
    atBottom: termBox.scrollHeight - termBox.scrollTop - termBox.clientHeight < 36,
  } : null;
  const drawerBody = UI.drawer ? $('.drawer-body') : null;
  const drawerTop = drawerBody ? drawerBody.scrollTop : 0;
  const modalEl = $('#modal');
  const modalScrollEl = modalEl?.open ? (modalEl.querySelector('.modal-body') || modalEl) : null;
  const modalTop = modalScrollEl ? modalScrollEl.scrollTop : 0;

  const alerts = alertCount();
  const topSig = computeTopSig(alerts);
  if (topSig !== lastTopSig || !UI.topShell) {
    lastTopSig = topSig;
    renderTop();
  }
  renderView();
  if (UI.drawer || lastDrawerMounted) {
    renderDrawer();
    lastDrawerMounted = Boolean(UI.drawer);
  }
  const wantModal = S.authNeeded ? 'auth' : UI.modal;
  if (wantModal || lastModalWant) {
    renderModal();
    lastModalWant = wantModal;
  }

  if (UI.drawer && drawerTop) {
    const nextDrawer = $('.drawer-body');
    if (nextDrawer) nextDrawer.scrollTop = drawerTop;
  }
  if (modalEl?.open && modalTop) {
    const nextModalScroll = modalEl.querySelector('.modal-body') || modalEl;
    nextModalScroll.scrollTop = modalTop;
  }
  const nextTitle = `${alerts ? `(${alerts}) ` : ''}${L('starfane · 控制面', 'starfane · Control Plane')}`;
  if (document.title !== nextTitle) document.title = nextTitle;
  if (!persistentWsMounted) {
    const nextTerm = $('.term-viewport');
    if (nextTerm && nextTerm !== termBox) {
      const samePane = termScroll && termScroll.sid === nextTerm.dataset.sid && termScroll.mode === nextTerm.dataset.mode;
      nextTerm.scrollTop = (!samePane || termScroll.atBottom) ? nextTerm.scrollHeight : termScroll.top;
      syncScrollLatestBtn(nextTerm);
    }
  }
  if (fk) {
    const n = document.querySelector(`[data-draft="${CSS.escape(fk)}"]`);
    if (n && n !== document.activeElement) {
      n.focus({ preventScroll: true });
      if (sel) { try { n.setSelectionRange(sel[0], sel[1]); } catch { /* ignore */ } }
    }
  }
}

function go(view, arg) {
  location.hash = `#/${view}${arg ? `/${enc(arg)}` : ''}`;
}

function openSession(id) {
  const prevSid = UI.selSession;
  onLeaveSession(prevSid, id);
  UI.selSession = id;
  UI.arg = id;
  UI.mobileSessionsOpen = false;
  const s = S.sessions.get(id);
  if (s) loadSessionOutput(s, { silent: false });
  const wantHash = `#/workspace/${enc(id)}`;
  if (UI.view !== 'workspace' || location.hash !== wantHash) go('workspace', id);
  else rerender();
}

function route() {
  const prevSid = UI.selSession;
  UI.mobileSessionsOpen = false;
  const raw = location.hash.replace(/^#\/?/, '') || 'workspace';
  const slash = raw.indexOf('/');
  let v = slash === -1 ? raw : raw.slice(0, slash);
  const a = slash === -1 ? '' : raw.slice(slash + 1);
  if (v === 'sessions') v = 'workspace';
  if (v === 'debug') { v = 'pipelines'; UI.pipeFilter = 'debug'; }
  UI.view = VIEWS.includes(v) ? v : 'workspace';
  if (a) {
    try { UI.arg = decodeURIComponent(a); } catch { UI.arg = a; }
  } else {
    UI.arg = null;
  }
  if (UI.view === 'workspace' && UI.arg && S.sessions.has(UI.arg)) {
    if (prevSid !== UI.arg) onLeaveSession(prevSid, UI.arg);
    UI.selSession = UI.arg;
  }
  if (UI.view === 'reviews') {
    if (S.reviewsState === 'idle' || S.reviewsState === 'err') loadReviews();
    if (S.precisionState === 'idle') loadPrecision();
  }
  const s = currentSession();
  if (UI.view === 'workspace' && s) {
    if (s.agent !== 'shell' && !S.transcripts.has(s.session_id)) loadTranscript(s.session_id, { silent: false });
    if (s.pane && !S.previews.has(pvKeyOf(s.pane))) loadPreview(s.pane, { mode: pvModeOf(s.pane), silent: false });
  }
  schedule();
}

